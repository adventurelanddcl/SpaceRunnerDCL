/** Total gems every map spawns (and that must be collected to finish). */
export const TOTAL_GEMS = 20;

/**
 * How many gems of each type a map spawns. Each distribution totals TOTAL_GEMS.
 * Gem value rises from gem1 (lowest) to gem4 (highest).
 */

const gemDistributions: Record<number, Record<number, number>> = {
  1: { 1: 20 },
  2: { 1: 15, 2: 5 },
  3: { 1: 10, 2: 10 },
  4: { 1: 5, 2: 12, 3: 3 },
  5: { 2: 14, 3: 6 },
  6: { 2: 10, 3: 9, 4: 1 },
  7: { 2: 5, 3: 12, 4: 3 },
  8: { 3: 15, 4: 5 },
  9: { 3: 12, 4: 8 },
  10: { 3: 10, 4: 10 },
};

/** In-place shuffle. */
function shuffle<T>(arr: T[]): T[] {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * Picks the gems to spawn for a map: exactly TOTAL_GEMS positions (provided the
 * pool has at least that many), each assigned a gem type per the map's
 * distribution. Positions and type assignment are randomized each run.
 */
export function pickGems(map: number): SelectedGem[] {
  const pool = pools[map] ?? [];
    const distribution = gemDistributions[map] ?? { 1: TOTAL_GEMS };

  // Build the exact list of gem types for this map (totals TOTAL_GEMS), shuffled
  // so the types are spread randomly across the chosen positions.
  const gemTypes: number[] = [];
  for (const typeStr of Object.keys(distribution)) {
    const type = Number(typeStr);
      for (let n = 0; n < distribution[type]; n++) gemTypes.push(type);
  }
  shuffle(gemTypes);

  // Exactly as many random positions as we have gem types (capped by pool size).
  const positions = shuffle([...pool]).slice(0, gemTypes.length);

  return positions.map((p, i) => ({ x: p.x, y: p.y, z: p.z, gemType: gemTypes[i] }));
}
